"""Regenerate the pinned Unicode canonical-normalization data from Python's UCD."""
from pathlib import Path
import unicodedata as ucd

if ucd.unidata_version != "15.0.0":
    raise SystemExit("Use the approved Python 3.12 / Unicode 15.0.0 database")
target = Path(__file__).resolve().parents[3] / "contracts" / "unicode_data.gd"
tables = {"DECOMPOSE": {}, "CLASS": {}, "COMPOSE": {}}
for cp in range(0x110000):
    char = chr(cp)
    klass = ucd.combining(char)
    if klass:
        tables["CLASS"][cp] = klass
    raw = ucd.decomposition(char)
    if raw and not raw.startswith("<"):
        tables["DECOMPOSE"][cp] = [ord(ch) for ch in ucd.normalize("NFD", char)]
        pair = [int(x, 16) for x in raw.split()]
        if len(pair) == 2 and ucd.normalize("NFC", "".join(map(chr, pair))) == char:
            tables["COMPOSE"][(pair[0] << 21) | pair[1]] = cp
lines = ["# Generated by game/tests/p1/contracts/generate_unicode.py (Unicode 15.0.0).",
         "extends RefCounted", ""]
for name, entries in tables.items():
    lines.append("const " + name + " := {")
    lines.extend(f"\t{k}: {v}," for k, v in entries.items())
    lines.extend(["}", ""])
target.write_text("\n".join(lines), encoding="utf-8", newline="\n")
